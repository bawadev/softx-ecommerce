import { test, expect } from '@playwright/test'

/**
 * Golden journey (Phase 3 capstone): login -> product -> cart -> checkout ->
 * order confirmed -> order listed under /en/orders.
 *
 * Uses the SMOKE-* products (seeding + cleanup instructions live in
 * smoke.spec.ts's header) and the customer account created by
 * `npm run db:seed` (apps/factorybay/scripts/seed-db.ts):
 *   test@example.com / Customer123!
 *
 * UI reality (verification duties against the real components):
 * - Login (src/app/[locale]/login/page.tsx, itself the client component):
 *   labeled inputs "Email" / "Password", submit button "Sign In". There is no
 *   toast — failures render in a red error div; success performs a FULL page
 *   reload (window.location.href) to /en/shop for CUSTOMER accounts.
 * - PDP: no default variant — pick a size, then a color, before "Add to Cart"
 *   enables; post-add feedback is the "Added to cart!" message (same as
 *   cart.spec.ts).
 * - Checkout (CheckoutPageClient.tsx): SHIP delivery is the default radio, so
 *   the address fields render immediately. Required labeled inputs: "Full
 *   Name", "Phone Number", "Address Line 1", "City", "State", "Postal Code".
 *   "Country" is prefilled ("United States"), the email input is prefilled and
 *   disabled for authenticated users, and "Address Line 2" is optional.
 *   Submit button: "Place Order". On success the client router.push()es to
 *   /en/order/{id}, whose confirmation page shows the heading "Order
 *   Confirmed!" and the order number (format FB-<timestamp>, generated by the
 *   engine's order repository) right under the "Order Number" label.
 * - /en/orders ("My Orders") lists every order number the same way.
 *
 * NOTE: this spec PLACES A REAL ORDER as the seeded customer in the local dev
 * Neo4j — acceptable for a dev database (per the Phase 3 plan); the order is
 * intentionally NOT deleted afterwards. Each run creates a new FB-<timestamp>
 * order, so the /en/orders assertion targets THIS run's exact order number
 * rather than a count. A successful order clears the customer's cart
 * (engine-side), so consecutive runs start from an empty user cart.
 */
test('customer logs in, checks out, and sees the order in their orders', async ({
  page,
}) => {
  // --- Login as the seeded customer (full-page reload to /en/shop) ---
  await page.goto('/en/login')
  await page.getByLabel('Email').fill('test@example.com')
  // exact: the password field's eye toggle carries aria-label "Show password"
  await page.getByLabel('Password', { exact: true }).fill('Customer123!')
  await page.getByRole('button', { name: 'Sign In' }).click()
  await page.waitForURL('**/en/shop')

  // --- Add SMOKE-UST-001 ("Classic Cotton T-Shirt") to the user cart ---
  await page.getByRole('link', { name: /classic cotton/i }).first().click()
  await page.waitForURL('**/product/**')

  const sizeChoices = page.locator(
    'h3:has-text("Select Size") + div button:not([disabled])'
  )
  await sizeChoices.first().click()

  const colorChoices = page.locator(
    'h3:has-text("Select Color") + div button:not([disabled])'
  )
  await colorChoices.first().click()

  const addToCart = page.getByRole('button', { name: 'Add to Cart' })
  await expect(addToCart).toBeEnabled()
  await addToCart.click()
  await expect(page.getByText('Added to cart!')).toBeVisible()

  // --- Checkout: fill the shipping form and place the order ---
  await page.goto('/en/checkout')
  await expect(page.getByRole('heading', { name: 'Checkout' })).toBeVisible()

  await page.getByLabel('Full Name').fill('Smoke Customer')
  await page.getByLabel('Phone Number').fill('+94770000000')
  await page.getByLabel('Address Line 1').fill('1 Test Street')
  await page.getByLabel('City').fill('Colombo')
  await page.getByLabel('State').fill('Western')
  await page.getByLabel('Postal Code').fill('00100')
  // "Country" is prefilled and the SHIP delivery radio is already selected.

  await page.getByRole('button', { name: 'Place Order' }).click()
  await page.waitForURL('**/en/order/**')

  // --- Confirmation page shows this order's number ---
  await expect(
    page.getByRole('heading', { name: 'Order Confirmed!' })
  ).toBeVisible()
  const orderNumberLine = page.locator('p:has-text("Order Number") + p').first()
  await expect(orderNumberLine).toHaveText(/^FB-\d+$/)
  const orderNumber = ((await orderNumberLine.textContent()) ?? '').trim()
  expect(orderNumber).toMatch(/^FB-\d+$/)

  // --- The order is listed under /en/orders ---
  await page.goto('/en/orders')
  await expect(page.getByRole('heading', { name: 'My Orders' })).toBeVisible()
  await expect(page.getByText(orderNumber)).toBeVisible()
})
